"""Location definitions and lookup tables for the Croc 2 Archipelago World."""

import json
import pkgutil
from typing import Dict, List, Set
from BaseClasses import Location


class Croc2Location(Location):
    game: str = "Croc 2"


def _load_locations_data() -> List[dict]:
    raw = pkgutil.get_data(__package__ or "worlds.croc2", "data/locations.json")
    if raw is None:
        raise RuntimeError("Failed to load worlds/croc2/data/locations.json")
    return json.loads(raw.decode("utf-8"))


def _load_level_mapping() -> dict:
    raw = pkgutil.get_data(__package__ or "worlds.croc2", "data/level_mapping.json")
    if raw is None:
        raise RuntimeError("Failed to load worlds/croc2/data/level_mapping.json")
    return json.loads(raw.decode("utf-8"))


LEVEL_MAPPING: dict = _load_level_mapping()


def _load_logic() -> List[dict]:
    """Per stage: what every White Crystal number, coloured crystal, Golden Gobbo and stage clear needs.

    Generated by tools/build_logic.py from data/logic.json. A requirement is a list of alternatives; each
    alternative is a list of item names that are all needed ("@GG" = the stage's five coloured crystals).
    """
    raw = pkgutil.get_data(__package__ or "worlds.croc2", "data/logic_compiled.json")
    return json.loads(raw.decode("utf-8"))["stages"] if raw else []


LOGIC: List[dict] = _load_logic()


def _load_consumable_need() -> Dict[str, int]:
    """How many of each consumable must be held before a check behind one of its markers is in logic."""
    raw = pkgutil.get_data(__package__ or "worlds.croc2", "data/logic_compiled.json")
    return json.loads(raw.decode("utf-8")).get("consumable_need", {}) if raw else {}


CONSUMABLE_NEED: Dict[str, int] = _load_consumable_need()
LOGIC_BY_NAME: Dict[str, dict] = {entry["name"].lower(): entry for entry in LOGIC}


def _build_full_location_table() -> List[dict]:
    base_locs = _load_locations_data()
    # Dynamically append the 2,000 individual White Crystal locations (1..100 across all 20 stages)
    # IDs: 7211001 .. 7213000 (stage_idx * 100 + crystal_idx)
    stage_idx = 0
    for hub in LEVEL_MAPPING["hubs"]:
        hub_name = hub["name"]
        for lvl in hub["levels"]:
            door_num = lvl["door_num"]
            region_name = f"{hub_name} - {lvl['name']}"
            wad = lvl["wad"]
            door_id = lvl["door_id"]
            reqs = list(lvl.get("requires", []))
            for c_idx in range(1, 101):
                loc_id = 7211000 + stage_idx * 100 + c_idx
                # "White Crystal N" is one specific crystal (docs/crystal_ids.md), and its requirement comes from
                # the per-stage logic (docs/logic.md). The 20th door has no real stage; it keeps the old guess.
                info = LOGIC[stage_idx] if stage_idx < len(LOGIC) else None
                c_reqs = ([] if c_idx <= 25 else reqs) if info is None else []
                c_dnf = info["numbers"][c_idx - 1] if info is not None else None
                base_locs.append({
                    "id": loc_id,
                    "name": f"{lvl['name']} - White Crystal {c_idx}",
                    "region": region_name,
                    "category": "White Crystals",
                    "wad": wad,
                    "door_id": door_id,
                    "crystal_index": c_idx,
                    "stage_index": stage_idx,
                    "requires": c_reqs,
                    "requires_dnf": c_dnf,
                })
            stage_idx += 1
    # Coloured crystals, Golden Gobbos and stage clears of the mapped stages take their requirement from the
    # same logic. Location names are "<stage name> - <Colour> Crystal" / "- Golden Gobbo" / "- Stage Clear".
    for entry in base_locs:
        if "requires_dnf" in entry or " - " not in entry.get("name", ""):
            continue
        stage_name, _, what = entry["name"].rpartition(" - ")
        info = LOGIC_BY_NAME.get(stage_name.lower())
        if info is None:
            continue
        if what.endswith(" Crystal") and info["colours"].get(what[:-8]) is not None:
            entry["requires_dnf"] = info["colours"][what[:-8]]
        elif what == "Golden Gobbo":
            entry["requires_dnf"] = info["golden"]
        elif what == "Stage Clear":
            entry["requires_dnf"] = info["clear"]
    return base_locs


LOCATION_TABLE: List[dict] = _build_full_location_table()

LOCATION_NAME_TO_ID: Dict[str, int] = {entry["name"]: entry["id"] for entry in LOCATION_TABLE}
LOCATION_ID_TO_NAME: Dict[int, str] = {entry["id"]: entry["name"] for entry in LOCATION_TABLE}
LOCATION_NAME_TO_DATA: Dict[str, dict] = {entry["name"]: entry for entry in LOCATION_TABLE}

LOCATION_NAME_GROUPS: Dict[str, Set[str]] = {}
for _entry in LOCATION_TABLE:
    _cat = _entry.get("category", "Miscellaneous")
    LOCATION_NAME_GROUPS.setdefault(_cat, set()).add(_entry["name"])

