"""Generate src/launcher/Croc2DataGenerated.cs: the launcher's built-in item and location names.

  gen_launcher_data.py

The launcher shows item and location names in its activity log. It used to carry a hand-written table whose ids
no longer matched the mod's. This writes the table from the same files the mod and the apworld use
(worlds/croc2/data/items.json, locations.json, level_mapping.json), so they can't drift. Run it after changing
any of those.
"""
import json
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(REPO, 'worlds', 'croc2', 'data')


def cs(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    items = json.load(open(os.path.join(DATA, 'items.json'), encoding='utf-8'))
    locs = json.load(open(os.path.join(DATA, 'locations.json'), encoding='utf-8'))
    mapping = json.load(open(os.path.join(DATA, 'level_mapping.json'), encoding='utf-8'))
    stages = [lvl['name'] for hub in mapping['hubs'] for lvl in hub['levels']]
    out = ['// Generated by tools/gen_launcher_data.py from worlds/croc2/data. Do not edit.',
           'namespace Croc2Launcher',
           '{',
           '    public static class Croc2DataGenerated',
           '    {',
           '        // id, name, classification',
           '        public static readonly object[][] Items = new object[][]',
           '        {']
    for e in sorted(items, key=lambda e: e['id']):
        out.append('            new object[] { %d, %s, %s },' % (e['id'], cs(e['name']), cs(e.get('classification', 'filler'))))
    out += ['        };', '',
            '        // id, name. White crystal checks are not listed: they are 7211000 + stage * 100 + number.',
            '        public static readonly object[][] Locations = new object[][]',
            '        {']
    for e in sorted(locs, key=lambda e: e['id']):
        out.append('            new object[] { %dL, %s },' % (e['id'], cs(e['name'])))
    out += ['        };', '',
            '        // Stage names in check order (stage 0 first).',
            '        public static readonly string[] Stages = new string[]',
            '        {']
    for name in stages:
        out.append('            %s,' % cs(name))
    out += ['        };', '    }', '}', '']
    path = os.path.join(REPO, 'src', 'launcher', 'Croc2DataGenerated.cs')
    with open(path, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write('\n'.join(out))
    print('wrote %d items, %d locations, %d stages' % (len(items), len(locs), len(stages)))


if __name__ == '__main__':
    main()
