"""Give every white crystal in the 19 randomized stages its own permanent number (1..100 per stage).

  crystal_ids.py <folder with the level .WAD files> [--write]

Numbering, per stage: the stage's maps in name order (M001, M002, ...), and inside a map the placement table's
own order. A loose crystal ("crystal") takes one number; a smash box takes five (its five crystals); a ring of
crystals takes eight. Whatever is left up to 100 are the stage's awarded crystals (chests, race prizes, rescued
Gobbos, puzzle rewards: see docs/level_objects.md), numbered after the placed ones.

--write regenerates src/hook/crystal_ids.inc (the table the mod uses), docs/crystal_ids.md (the readable list)
and worlds/croc2/data/crystal_ids.json (what the apworld needs: which numbers are box crystals).
"""
import glob
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import strat_disasm  # noqa: E402

# Stage order = kStageDoors in src/hook/croc2_ap_hook.cpp (index = the mod's stage number).
STAGES = ['T1L2', 'T1L3', 'T1L4', 'T1L5', 'T1L6', 'T2L2', 'T2L3', 'T2L5', 'T2L6', 'T2L7',
          'T3L2', 'T3L3', 'T3L4', 'T3L5', 'T3L7', 'T4L2', 'T4L3', 'T4L5', 'T4L6']
NAMES = ['Find the Key! Save the Gobbo!', 'Find 5 Lost Treasure Chests', "Get the Gobbo's Sandwich!",
         'Croc Vs Dantini Boat Race', 'Save the Bird from the Thief', 'Save the Ice Trapped Gobbos!',
         'Chase the Choo Choo Train', "It's just Snowball Madness!", 'Hang Glider Valley',
         "KaBooom! It's Roger Red Ant", 'Find the Wheels in the Jungle!', 'Find the Wheels in the Mine!',
         'Race Day at Goldrock', "Climb The Devil's Tower", 'Save 50 Trapped Gobbos!', 'Save 30 Gobbo babies!',
         'Up the Waterfall', 'Bride of the Dungeon of Defright', "Goo Man Chu's Tower"]
LOOSE, BOX, RING, AWARD = 0, 1, 2, 3
KIND = {LOOSE: 'crystal', BOX: 'smash box (5)', RING: 'ring of crystals (8)', AWARD: 'awarded'}


def stage_sources(root, prefix):
    out = []
    n = 1
    for path in sorted(glob.glob(os.path.join(root, prefix + 'M*.WAD'))):
        wad = os.path.basename(path)[:-4]
        try:
            d, base, recs, ents, names = strat_disasm.load(path)
        except Exception:
            continue
        for r in recs:
            name = names.get(r[12], '?')
            if name == 'crystal':
                kind, count = LOOSE, 1
            elif 'Smash Box' in name:
                kind, count = BOX, 5
            elif name == 'ring of crystals':
                kind, count = RING, 8
            else:
                continue
            out.append((wad, kind, r[8], r[9], r[10], n, count, name))
            n += count
    return out, n - 1


def main():
    root = sys.argv[1]
    write = '--write' in sys.argv
    rows = []
    md = ['# Crystal IDs', '',
          'Every white crystal in the 19 randomized stages has a permanent number, 1 to 100 within its stage. The',
          'check "<stage> - White Crystal N" is always the same crystal. Generated by `tools/crystal_ids.py` from the',
          'level files; do not edit by hand.', '',
          'Positions are the game\'s own units (x, y, z). A smash box\'s five numbers are its five crystals, in the',
          'order they are collected; the same for a ring\'s eight. "Awarded" numbers are crystals the level hands out',
          '(chests, race prizes, rescued Gobbos, puzzle rewards), in the order they are earned.', '']
    for si, prefix in enumerate(STAGES):
        src, placed = stage_sources(root, prefix)
        if placed > 100:
            raise SystemExit('%s has %d placed crystals' % (prefix, placed))
        print('%s %-34s placed %3d  awarded %3d' % (prefix, NAMES[si], placed, 100 - placed))
        md += ['## %s %s' % (prefix, NAMES[si]), '', '| Numbers | What | Map | Position |', '|---|---|---|---|']
        for wad, kind, x, y, z, first, count, name in src:
            rows.append((si, wad, kind, x, y, z, first, count))
            num = str(first) if count == 1 else '%d-%d' % (first, first + count - 1)
            md.append('| %s | %s | %s | %d, %d, %d |' % (num, KIND[kind] if kind != BOX else name + ' (5)', wad, x, y, z))
        if placed < 100:
            rows.append((si, prefix + 'M001', AWARD, 0, 0, 0, placed + 1, 100 - placed))
            md.append('| %d-100 | awarded by the level | | |' % (placed + 1))
        md.append('')
    if write:
        repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        with open(os.path.join(repo, 'src', 'hook', 'crystal_ids.inc'), 'w', newline='\n') as f:
            f.write('// Generated by tools/crystal_ids.py from the level files. Do not edit.\n')
            f.write('// {stage, map, kind (0 loose, 1 box, 2 ring, 3 awarded), x, y, z, first number, count}\n')
            for si, wad, kind, x, y, z, first, count in rows:
                f.write('{%d, "%s", %d, %d, %d, %d, %d, %d},\n' % (si, wad, kind, x, y, z, first, count))
        with open(os.path.join(repo, 'docs', 'crystal_ids.md'), 'w', newline='\n', encoding='utf-8') as f:
            f.write('\n'.join(md) + '\n')
        # The apworld's copy: per stage, the kind of each number 1..100 and the numbers assumed reachable with a
        # plain jump (the first ten loose crystals of the stage's first map).
        import json
        stages = []
        for si in range(len(STAGES)):
            kinds = [AWARD] * 100
            early = []
            first_map = None
            for s2, wad, kind, x, y, z, first, count in rows:
                if s2 != si:
                    continue
                for n in range(first, first + count):
                    kinds[n - 1] = kind
                if kind == LOOSE:
                    first_map = first_map or wad
                    if wad == first_map and len(early) < 10:
                        early.append(first)
            stages.append({'stage': STAGES[si], 'kinds': kinds, 'early': early})
        with open(os.path.join(repo, 'worlds', 'croc2', 'data', 'crystal_ids.json'), 'w', newline='\n') as f:
            json.dump({'kinds': {'0': 'loose', '1': 'smash box', '2': 'ring', '3': 'awarded'}, 'stages': stages}, f, separators=(',', ':'))
        print('wrote %d rows' % len(rows))


if __name__ == '__main__':
    main()
